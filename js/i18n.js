class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('frndspace_lang') || 'en';
    this.init();
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  }

  applyLanguage(lang) {
    if (!I18N_DICTIONARY[lang]) {
      lang = 'en';
    }
    this.currentLang = lang;
    localStorage.setItem('frndspace_lang', lang);

    // Set dir attribute for Arabic
    if (lang === 'ar') {
      document.body.setAttribute('dir', 'rtl');
      document.documentElement.setAttribute('lang', 'ar');
    } else {
      document.body.removeAttribute('dir');
      document.documentElement.setAttribute('lang', lang);
    }

    const dict = I18N_DICTIONARY[lang];
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Update placeholders
    const placeholderEls = document.querySelectorAll('[data-i18n-placeholder]');
    placeholderEls.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    // Update active state in UI
    const currentLangLabel = document.getElementById('currentLangLabel');
    if (currentLangLabel) {
      const langNames = {
        en: '🇬🇧 EN',
        te: '🇮🇳 తెలుగు',
        hi: '🇮🇳 हिन्दी',
        es: '🇪🇸 ES',
        fr: '🇫🇷 FR',
        de: '🇩🇪 DE',
        it: '🇮🇹 IT',
        ar: '🇦🇪 العربية',
        ja: '🇯🇵 日本語',
        ru: '🇷🇺 RU'
      };
      currentLangLabel.textContent = langNames[lang] || lang.toUpperCase();
    }

    // Dispatch custom event
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  bindEvents() {
    const langBtn = document.getElementById('langBtn');
    const langDropdown = document.getElementById('langDropdown');

    if (langBtn && langDropdown) {
      langBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        langDropdown.classList.toggle('open');
        const themeDropdown = document.getElementById('themeDropdown');
        if (themeDropdown) themeDropdown.classList.remove('open');
      });

      document.addEventListener('click', () => {
        langDropdown.classList.remove('open');
      });

      const options = langDropdown.querySelectorAll('.lang-option');
      options.forEach(opt => {
        opt.addEventListener('click', (e) => {
          e.stopPropagation();
          const selectedLang = opt.getAttribute('data-lang');
          this.applyLanguage(selectedLang);
          langDropdown.classList.remove('open');
        });
      });
    }
  }
}

// Global instance
window.i18n = new I18nManager();
